def apply(book, records, flags, line_checks, classify, check_kinds):
    """Apply this book's repairs to the built records in place; update `flags` (the builder's
    list) for the changed lines; return the log records."""
    tvu = TVU.format(TVU_LIB[book])
    by_n = {r["number"]: r for r in records}
    log = []
    changed = {}

    def variant(r, line):
        return next((v for v in r["variants"] if v["line"] == line), None)

    for b, n, line, old, new, kind, changes in EDITS:
        if b != book:
            continue
        r = by_n[n]
        if r["tamil"][line - 1] != old:
            raise SystemExit(f"{book}:{n} line {line} is {r['tamil'][line - 1]!r}, expected {old!r}")
        r["tamil"][line - 1] = new
        changed[(n, line)] = old
        v = variant(r, line)
        if v is not None:
            v.setdefault("pm", old)
            c = classify(new, v["stc"]) if v.get("stc") else "reading"
            v["kind"] = "repaired" if c == "same" else c
            v["kept"] = ("pm, poet's name moved to `poet`" if kind == "colophon_in_verse"
                         else "pm, repaired from tvu")
            v["tvu"] = "stc"
        if kind == "colophon_in_verse":
            r["poet"] = POETS[(book, n)]
        log.append({"book": book, "poem": r["id"], "number": n, "action": "changed", "kind": kind,
                    "field": "tamil", "line": line, "old": old, "new": new,
                    "authority": [tvu, STC] if kind != "colophon_in_verse" else [tvu],
                    "changes": [{"old": o, "new": nw, "rule": rule, "readings": {"tvu": t, "stc": s}}
                                for o, nw, rule, t, s in changes],
                    "note": f"poet's name moved to `poet`: {POETS[(book, n)]}"
                    if kind == "colophon_in_verse" else None})
    for b, n, line, words, t, s, note in KEPT:
        if b != book:
            continue
        r = by_n[n]
        if words not in r["tamil"][line - 1]:
            raise SystemExit(f"{book}:{n} line {line} lacks {words!r}")
        v = variant(r, line)
        if v is not None:
            v["tvu"] = "neither"
        log.append({"book": book, "poem": r["id"], "number": n, "action": "kept", "kind": "reading",
                    "field": "tamil", "line": line, "old": r["tamil"][line - 1], "new": None,
                    "authority": None, "changes": [{"old": words, "new": None, "rule": None,
                                                    "readings": {"tvu": t, "stc": s}}],
                    "note": "tvu agrees with neither; ours kept" + (f"; {note}" if note else "")})
    agrees = set(TVU_AGREES[book])
    for r in records:
        for v in r["variants"]:
            if v["kind"] in ("reading", "unlike") and "tvu" not in v:
                v["tvu"] = "pm" if (r["number"], v["line"]) in agrees else "spelling"

    # flags: the changed lines are checked again, the poet flags of the two colophons go
    ids = {r["number"]: r["id"] for r in records}
    stale = {(ids[n], line) for n, line in changed}
    keep = [f for f in flags if not (f["book"] == book and (
        (f["kind"] in check_kinds and (f["id"], f["line"]) in stale) or
        (f["kind"] == "colophon" and f["id"] and (book, int(f["id"].split(":")[1])) in POETS)))]
    flags[:] = keep
    for rec in log:
        n, line = rec["number"], rec["line"]
        if rec["action"] == "changed":
            line_checks(book, rec["poem"], line, by_n[n]["tamil"][line - 1])
            detail = {"reading": "reading of tamilvu.org (U. V. Swaminatha Aiyar), which agrees with "
                                 "sangamtamil.com, replaces ours",
                      "conversion": "conversion fault of the e-text corrected by rule, confirmed by "
                                    "tamilvu.org and sangamtamil.com",
                      "tscii_rule": "TSCII 'தௌ ' read as தெள், as tamilvu.org has it (not தெளி)",
                      "colophon_in_verse": "poet's name printed at the end of the verse moved to "
                                           "`poet`"}[rec["kind"]]
            flags.append({"book": book, "id": rec["poem"], "kind": "repaired", "line": line,
                          "detail": detail, "text": f"{rec['old']} -> {rec['new']}"})
        else:
            c = rec["changes"][0]
            flags.append({"book": book, "id": rec["poem"], "kind": "variant", "line": line,
                          "detail": f"tamilvu.org reads {c['readings']['tvu']!r}, sangamtamil.com "
                                    f"{c['readings']['stc']!r}; ours ({c['old']!r}) kept",
                          "text": rec["old"]})

    log.sort(key=lambda x: (x["number"], x["action"] != "changed", x["line"]))
    seen = {}
    for rec in log:
        seen[rec["number"]] = seen.get(rec["number"], 0) + 1
        rec["id"] = f"{rec['poem']}:r{seen[rec['number']]}"
    for r in records:
        r["repairs"] = [rec["id"] for rec in log if rec["number"] == r["number"]]
    keys = ("id", "book", "poem", "number", "action", "kind", "field", "line", "old", "new",
            "authority", "changes", "note")
    return [{k: rec.get(k) for k in keys} for rec in log]
